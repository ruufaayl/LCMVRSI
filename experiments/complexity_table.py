#!/usr/bin/env python
"""Emit the complexity/memory table, generated from the live registered models.

Usage::

    uv run python experiments/complexity_table.py            # print to stdout
    uv run python experiments/complexity_table.py -o results/complexity_table.md

The numbers come straight from each model's ``complexity()`` and ``state_size``, so the table
cannot drift from the implementation. Cross-check against the hand-derived derivations in
``docs/architecture-review/README.md`` (section 5).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from lcmvrsi.analysis import complexity_table, render_markdown_table

_DOC_REF = "docs/architecture-review/README.md"


def main(argv: list[str] | None = None) -> str:
    p = argparse.ArgumentParser(description="Generate the model complexity/memory table.")
    p.add_argument("--models", nargs="+", default=None, help="Models (default: all registered).")
    p.add_argument("--seq-len", type=int, default=512)
    p.add_argument("--vocab-size", type=int, default=64)
    p.add_argument("-o", "--out", default=None, help="Write Markdown here instead of stdout.")
    args = p.parse_args(argv)

    rows = complexity_table(args.models, seq_len=args.seq_len, vocab_size=args.vocab_size)
    table = render_markdown_table(rows)
    doc = (
        "# Model complexity & memory (generated)\n\n"
        "Generated by `experiments/complexity_table.py` from the live registered models "
        "(`complexity()` and `state_size`). `T` = sequence length, `d` = model width. "
        f"Cross-check against the hand-derived derivations in `{_DOC_REF}` (section 5).\n\n"
        f"{table}\n"
    )

    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(doc, encoding="utf-8")
        print(f"complexity table -> {out}")
    else:
        print(doc)
    return doc


if __name__ == "__main__":
    main()
